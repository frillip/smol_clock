"""Generates the SPL's linker script, spl.gld, from Microchip's script for the
device, so it keeps its regions and its licence header:

  - the program region from SPL_START (0x000800) to the SPL record's row
    (0x001F80): 3008 instructions, nothing of the SPL anywhere else;
  - no reset vector and no IVT: both the IPL's (spl_vectors.s keeps the
    linker's own IVT out of the hex);
  - at 0x000800, GOTO __reset: the IPL starts the SPL there;
  - _ipl_crc32_flash at IPL_SERVICES (0x000200), the IPL's CRC-32 service.

Usage: python3 tools/gen_spl.py <p33EP256GP504.gld>
(from the XC16 install: support/dsPIC33E/gld/p33EP256GP504.gld). Writes
dspic_spl/spl.gld, which is committed: run this again only for another XC16
version. Addresses come from common/boot_layout.h.
"""
import os
import re
import sys

HERE = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
LAYOUT = os.path.join(HERE, "..", "common", "boot_layout.h")


def layout():
    values = {}
    with open(LAYOUT) as handle:
        for line in handle:
            match = re.match(r"\s*#define\s+(\w+)\s+(?:BOOT_UL\()?(0x[0-9A-Fa-f]+|\d+)\)?", line)
            if match:
                values[match.group(1)] = int(match.group(2), 0)
    return values


L = layout()


def goto(expression):
    # GOTO lit23: first word 0x04 << 16 | lit<15:0>, second word lit<22:16>,
    # each SHORT one 16-bit half of a program word, as the device's .reset.
    return ("    SHORT(%s);\n    SHORT(0x04);\n    SHORT((%s >> 16) & 0x7F);\n    SHORT(0);"
            % (expression, expression))


def spl_script(gld):
    end = gld.index("*/") + 2
    header, body = gld[:end], gld[end:]
    start, length = L["SPL_START"], L["SPL_RECORD_ADDRESS"] - L["SPL_START"]
    body, count = re.subn(r"program \(xr\)\s*: ORIGIN = 0x[0-9A-Fa-f]+,\s*LENGTH = 0x[0-9A-Fa-f]+",
                          "program (xr)   : ORIGIN = 0x%X,         LENGTH = 0x%X" % (start, length), body)
    assert count == 1, "program region"
    body, count = re.subn(r"__CODE_BASE = 0x[0-9A-Fa-f]+;", "__CODE_BASE = 0x%X;" % start, body)
    assert count == 1
    body, count = re.subn(r"__CODE_LENGTH = 0x[0-9A-Fa-f]+;", "__CODE_LENGTH = 0x%X;" % length, body)
    assert count == 1
    pattern = re.compile(r"#if !defined\(__CORESIDENT\) \|\| defined\(__DEFINE_RESET\)\n.*?#endif\n", re.S)
    body, count = pattern.subn("  /* No .reset: the reset vector is the IPL's. */\n", body)
    assert count == 1, ".reset"
    entry = ("  /*\n"
             "  ** The SPL's entry (common/boot_layout.h, SPL_START): the IPL jumps here.\n"
             "  */\n"
             "  .spl_entry 0x%X :\n"
             "  {\n%s\n"
             "  } >program\n\n" % (start, goto("ABSOLUTE(__reset)")))
    marker = "  /*\n  ** Interrupt Vector Tables"
    assert body.count(marker) == 1, "IVT comment"
    body = body.replace(marker, entry + marker)
    note = ("\n/*\n * The V2+ SPL (dspic_spl), pages 1-3 (common/boot_layout.h): code from\n"
            " * 0x%06X, its entry GOTO first, up to its record row at 0x%06X.\n"
            " * Generated by dspic_spl/tools/gen_spl.py from the device script. With\n"
            " * spl_vectors.s, which keeps the linker's own IVT out of the hex.\n */\n\n"
            "/* The IPL's CRC-32 service (common/boot_layout.h, ipl_crc32_flash): a\n"
            " * GOTO at IPL_SERVICES. */\n"
            "_ipl_crc32_flash = 0x%06X;\n" % (start, L["SPL_RECORD_ADDRESS"], L["IPL_SERVICES"]))
    return header + note + body


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    with open(sys.argv[1]) as handle:
        gld = handle.read().replace("\r\n", "\n")
    path = os.path.join(HERE, "spl.gld")
    with open(path, "w", newline="\n") as handle:
        handle.write(spl_script(gld))
    print("wrote dspic_spl/spl.gld")
    return 0


if __name__ == "__main__":
    sys.exit(main())
