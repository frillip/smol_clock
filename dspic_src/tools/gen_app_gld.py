"""Generates the application's linker script, app.gld, from Microchip's
script for the device, so it keeps its regions and its licence header:

  - the program region from APP_START (0x002000): nothing of the
    application below it, where the IPL and the SPL live;
  - no reset vector: the IPL's;
  - at 0x002000, GOTO __reset, then the forwarding table: a GOTO for each of
    the 254 IVT entries, to the application's handler if it has one, else to
    __DefaultInterrupt. The IPL's IVT points entry A at 0x002004 + 2(A - 4);
  - _ipl_crc32_flash at IPL_SERVICES (0x000200), the IPL's CRC-32 service.

platform/app_vectors.s keeps the linker's own IVT out of the hex and the
version-record page free. Addresses come from common/boot_layout.h.

Usage: python3 tools/gen_app_gld.py <p33EP256GP504.gld>
(from the XC16 install: support/dsPIC33E/gld/p33EP256GP504.gld). Writes
dspic_src/app.gld, which is committed: run this again only for another XC16
version.
"""
import os
import re
import sys

HERE = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
LAYOUT = os.path.join(HERE, "..", "common", "boot_layout.h")
VECTORS = 254
PROGRAM_END = 0x02AFEC  # the device script's program region ends here


def layout():
    values = {}
    with open(LAYOUT) as handle:
        for line in handle:
            match = re.match(r"\s*#define\s+(\w+)\s+(?:BOOT_UL\()?(0x[0-9A-Fa-f]+|\d+)\)?", line)
            if match:
                values[match.group(1)] = int(match.group(2), 0)
    return values


L = layout()


def vector_names(gld):
    """The IVT's handler names in order, from the script's old-style table
    (kept for XC16 before 1.26); the rest are InterruptN, as MCC names them."""
    block = re.search(r"\.ivt __IVT_BASE :(.*?)>ivt", gld, re.S)
    if block is None:
        raise SystemExit("no .ivt table in the script")
    names = re.findall(r"DEFINED\(__(\w+)\)", block.group(1))
    names += ["Interrupt%d" % (index - 8) for index in range(len(names), VECTORS)]
    if len(names) != VECTORS:
        raise SystemExit("%d vectors, expected %d" % (len(names), VECTORS))
    return names


def goto(expression):
    # GOTO lit23: first word 0x04 << 16 | lit<15:0>, second word lit<22:16>.
    # Each SHORT is one 16-bit half of a program word (the upper one holds
    # the upper byte and the phantom byte), as the device script's .reset.
    return ("    SHORT(%s);\n    SHORT(0x04);\n    SHORT((%s >> 16) & 0x7F);\n    SHORT(0);"
            % (expression, expression))


def entry_and_table(names):
    lines = ["  /*",
             "  ** The application's entry and interrupt forwarding table",
             "  ** (common/boot_layout.h): GOTO __reset at 0x%06X, then one GOTO" % L["APP_START"],
             "  ** (2 instructions) for each IVT entry, in order, to the handler if the",
             "  ** application has one, else __DefaultInterrupt. The IPL's IVT points",
             "  ** entry A at 0x%06X + 2*(A - 4)." % L["APP_FORWARD_TABLE"],
             "  */",
             "  .app_entry 0x%X :" % L["APP_START"],
             "  {",
             goto("ABSOLUTE(__reset)")]
    for name in names:
        lines.append("    /* %s */" % name)
        lines.append(goto("(DEFINED(__%s) ? ABSOLUTE(__%s) : ABSOLUTE(__DefaultInterrupt))" % (name, name)))
    lines += ["  } >program", ""]
    return "\n".join(lines) + "\n"


def app_script(gld):
    end = gld.index("*/") + 2
    header, body = gld[:end], gld[end:]
    start = L["APP_START"]
    body, count = re.subn(r"program \(xr\)\s*: ORIGIN = 0x[0-9A-Fa-f]+,\s*LENGTH = 0x[0-9A-Fa-f]+",
                          "program (xr)   : ORIGIN = 0x%X,        LENGTH = 0x%X" % (start, PROGRAM_END - start),
                          body)
    assert count == 1, "program region"
    body, count = re.subn(r"__CODE_BASE = 0x[0-9A-Fa-f]+;", "__CODE_BASE = 0x%X;" % start, body)
    assert count == 1
    body, count = re.subn(r"__CODE_LENGTH = 0x[0-9A-Fa-f]+;", "__CODE_LENGTH = 0x%X;" % (PROGRAM_END - start),
                          body)
    assert count == 1
    pattern = re.compile(r"#if !defined\(__CORESIDENT\) \|\| defined\(__DEFINE_RESET\)\n.*?#endif\n", re.S)
    body, count = pattern.subn("  /* No .reset: the reset vector is the IPL's. */\n", body)
    assert count == 1, ".reset"
    marker = "  /*\n  ** Interrupt Vector Tables"
    assert body.count(marker) == 1, "IVT comment"
    body = body.replace(marker, entry_and_table(vector_names(gld)) + marker)
    note = ("\n/*\n * The V2+ application, linked behind the IPL and the SPL (common/boot_layout.h):\n"
            " * from 0x%06X, its entry and forwarding table first. Generated by\n"
            " * dspic_src/tools/gen_app_gld.py from the device script. With\n"
            " * platform/app_vectors.s, which keeps the linker's own IVT out of the hex\n"
            " * and the version-record page free.\n */\n\n"
            "/* The IPL's CRC-32 service (common/boot_layout.h, ipl_crc32_flash): a\n"
            " * GOTO at IPL_SERVICES. Call it only with the IPL there. */\n"
            "_ipl_crc32_flash = 0x%06X;\n" % (L["APP_START"], L["IPL_SERVICES"]))
    return header + note + body


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    with open(sys.argv[1]) as handle:
        gld = handle.read().replace("\r\n", "\n")
    path = os.path.join(HERE, "app.gld")
    with open(path, "w", newline="\n") as handle:
        handle.write(app_script(gld))
    print("wrote dspic_src/app.gld")
    return 0


if __name__ == "__main__":
    sys.exit(main())
