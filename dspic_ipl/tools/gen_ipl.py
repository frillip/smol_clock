"""Generates the IPL's page-0 fixtures from Microchip's linker script for the
device, so they keep its regions and its licence header:

  ipl.gld          the device script with the program region cut to
                   0x000200-0x0007FF and the GOTO to ipl_crc32_flash placed
                   at IPL_SERVICES (0x000200) before anything else
  ipl_vectors.s    the IVT: every interrupt to the application's forwarding
                   slot, the traps to stubs that forward to it only while the
                   mailbox says the application is running, and reset
                   otherwise

Usage: python3 tools/gen_ipl.py <p33EP256GP504.gld>
(from the XC16 install: support/dsPIC33E/gld/p33EP256GP504.gld). Writes
into dspic_ipl/. Addresses come from common/boot_layout.h. The outputs are
committed: run this again only for another XC16 version.
"""
import os
import re
import sys

HERE = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
LAYOUT = os.path.join(HERE, "..", "common", "boot_layout.h")
VECTORS = 254
TRAPS = 8  # OscillatorFail .. ReservedTrap7: IVT entries 0x0004-0x0012


def layout():
    values = {}
    with open(LAYOUT) as handle:
        for line in handle:
            match = re.match(r"\s*#define\s+(\w+)\s+(?:BOOT_UL\()?(0x[0-9A-Fa-f]+|\d+)\)?", line)
            if match:
                values[match.group(1)] = int(match.group(2), 0)
    return values


L = layout()


def vector_names(gld):
    """The IVT's handler names in order, from the script's old-style table
    (kept for XC16 before 1.26); the rest are InterruptN, as MCC names them."""
    block = re.search(r"\.ivt __IVT_BASE :(.*?)>ivt", gld, re.S)
    if block is None:
        raise SystemExit("no .ivt table in the script")
    names = re.findall(r"DEFINED\(__(\w+)\)", block.group(1))
    names += ["Interrupt%d" % (index - 8) for index in range(len(names), VECTORS)]
    if len(names) != VECTORS:
        raise SystemExit("%d vectors, expected %d" % (len(names), VECTORS))
    return names


def slot(index):
    return L["APP_FORWARD_TABLE"] + 4 * index


def ipl_script(gld):
    end = gld.index("*/") + 2
    header, body = gld[:end], gld[end:]
    origin, length = L["IPL_SERVICES"], L["IPL_END"] - L["IPL_SERVICES"]
    body, count = re.subn(r"program \(xr\)\s*: ORIGIN = 0x[0-9A-Fa-f]+,\s*LENGTH = 0x[0-9A-Fa-f]+",
                          "program (xr)   : ORIGIN = 0x%X,         LENGTH = 0x%X" % (origin, length), body)
    assert count == 1, "program region"
    body, count = re.subn(r"__CODE_BASE = 0x[0-9A-Fa-f]+;", "__CODE_BASE = 0x%X;" % origin, body)
    assert count == 1
    body, count = re.subn(r"__CODE_LENGTH = 0x[0-9A-Fa-f]+;", "__CODE_LENGTH = 0x%X;" % length, body)
    assert count == 1
    services = ("  /*\n"
                "  ** The IPL's services table (common/boot_layout.h, IPL_SERVICES):\n"
                "  ** GOTO ipl_crc32_flash, before anything else in the program region.\n"
                "  ** The SPL and the application call it here.\n"
                "  */\n"
                "  .ipl_services 0x%X :\n"
                "  {\n"
                "    SHORT(ABSOLUTE(_ipl_crc32_flash));\n"
                "    SHORT(0x04);\n"
                "    SHORT((ABSOLUTE(_ipl_crc32_flash) >> 16) & 0x7F);\n"
                "    SHORT(0);\n"
                "  } >program\n\n" % L["IPL_SERVICES"])
    marker = "  /*\n  ** Interrupt Vector Tables"
    assert body.count(marker) == 1, "IVT comment"
    body = body.replace(marker, services + marker)
    note = ("\n/*\n * The IPL (dspic_ipl): page 0 only, the services GOTO at 0x%06X first.\n"
            " * Generated by dspic_ipl/tools/gen_ipl.py from the device script; the IVT\n"
            " * is ipl_vectors.s.\n */\n" % L["IPL_SERVICES"])
    return header + note + body


def ipl_vectors(names):
    running = L["MAILBOX_ADDRESS"] + 2 * L["MAILBOX_RUNNING"]
    lines = ["; The IPL's IVT and trap stubs. Generated by dspic_ipl/tools/gen_ipl.py",
             "; from the device script and common/boot_layout.h: do not edit.",
             ";",
             "; Every interrupt goes straight to the application's forwarding slot,",
             "; 0x%06X + 2 * (A - 4) for IVT entry A: no stage but the application" % L["APP_FORWARD_TABLE"],
             "; enables interrupts. Each trap goes to a stub, which forwards it to the",
             "; application's slot only while the mailbox says the application is",
             "; running (MAILBOX_RUNNING_VALUE), and resets otherwise: a trap in the",
             "; IPL or the SPL must never jump into an application that may be",
             "; half-written. Assembly, as a stub must leave the trap's frame and every",
             "; register as it found them. A stack error trap that cannot push resets",
             "; through a trap conflict.",
             "",
             "        .include \"xc.inc\"",
             "",
             "        .section .ivt, code, address(0x4), keep"]
    for index, name in enumerate(names):
        target = "ipl_trap_%d" % index if index < TRAPS else "0x%06X" % slot(index)
        lines.append("        .pword  %-16s ; %s" % (target, name))
    lines += ["", "        .text"]
    for index in range(TRAPS):
        lines += ["ipl_trap_%d: ; %s" % (index, names[index]),
                  "        push    W0",
                  "        push    W1",
                  "        mov     0x%04X, W0 ; mailbox.running" % running,
                  "        mov     #0x%04X, W1" % L["MAILBOX_RUNNING_VALUE"],
                  "        cp      W0, W1",
                  "        pop     W1",
                  "        pop     W0",
                  "        bra     nz, 1f",
                  "        goto    0x%06X" % slot(index),
                  "1:      reset",
                  ""]
    lines += ["        .end", ""]
    return "\n".join(lines)


def write(name, text):
    with open(os.path.join(HERE, name), "w", newline="\n") as handle:
        handle.write(text)
    print("wrote dspic_ipl/%s" % name)


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    with open(sys.argv[1]) as handle:
        gld = handle.read().replace("\r\n", "\n")
    write("ipl.gld", ipl_script(gld))
    write("ipl_vectors.s", ipl_vectors(vector_names(gld)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
